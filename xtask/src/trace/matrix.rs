//! The traceability matrix: feature → tests → last result, as
//! `target/trace/matrix.md` (for people, attached to CI runs) and
//! `target/trace/matrix.json` (for tools such as the PR report).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use serde::Serialize;

use super::catalog::Feature;
use super::results::{Outcome, Results};
use super::tests_covering;
use crate::cmd::TRACE_DIR;
use crate::tags::Index;

#[derive(Serialize)]
struct Row<'a> {
    #[serde(flatten)]
    feature: &'a Feature,
    tests: Vec<TestResult<'a>>,
}

#[derive(Serialize)]
struct TestResult<'a> {
    id: &'a str,
    /// `None` when the test didn't run in this run.
    result: Option<Outcome>,
}

/// Writes both files and returns the Markdown path.
pub fn write(
    root: &Path,
    features: &BTreeMap<String, Feature>,
    index: &Index,
    results: &Results,
) -> Result<PathBuf> {
    let rows: Vec<Row<'_>> = features
        .values()
        .map(|feature| Row {
            feature,
            tests: tests_covering(index, &feature.id)
                .map(|t| TestResult {
                    id: &t.id,
                    result: results.get(&t.id).copied(),
                })
                .collect(),
        })
        .collect();

    let dir = root.join(TRACE_DIR);
    fs::create_dir_all(&dir).with_context(|| format!("creating {}", dir.display()))?;
    let json = serde_json::to_string_pretty(&rows).context("serialising the matrix")?;
    fs::write(dir.join("matrix.json"), json + "\n").context("writing matrix.json")?;
    let path = dir.join("matrix.md");
    fs::write(&path, markdown(&rows, index.len())).context("writing matrix.md")?;
    Ok(path)
}

fn markdown(rows: &[Row<'_>], test_count: usize) -> String {
    let mut md = String::from("# Traceability matrix\n\n");
    let _ = writeln!(
        md,
        "Generated by `cargo xtask trace` from {test_count} tagged tests and docs/claude/features.md.\n"
    );
    md.push_str("| Feature | Phase | Status | Tests | Last run |\n|---|---|---|---|---|\n");
    for row in rows {
        let f = row.feature;
        let (tests, last_run) = if row.tests.is_empty() {
            ("no tests yet".to_owned(), String::new())
        } else {
            (row.tests.len().to_string(), summary(&row.tests))
        };
        let _ = writeln!(
            md,
            "| {} {} | {} | {} | {tests} | {last_run} |",
            f.id,
            f.name,
            f.phase,
            f.status.symbol()
        );
    }

    md.push_str("\n## Tests per feature\n");
    for row in rows.iter().filter(|r| !r.tests.is_empty()) {
        let _ = writeln!(md, "\n### {} {}\n", row.feature.id, row.feature.name);
        for test in &row.tests {
            let _ = writeln!(md, "- `{}`: {}", test.id, outcome_word(test.result));
        }
    }
    md
}

/// "3 passed, 1 failed", counting tests that didn't run as "not run".
fn summary(tests: &[TestResult<'_>]) -> String {
    let mut counts: BTreeMap<&str, usize> = BTreeMap::new();
    for test in tests {
        *counts.entry(outcome_word(test.result)).or_default() += 1;
    }
    counts
        .iter()
        .map(|(word, n)| format!("{n} {word}"))
        .collect::<Vec<_>>()
        .join(", ")
}

fn outcome_word(result: Option<Outcome>) -> &'static str {
    match result {
        Some(Outcome::Passed) => "passed",
        Some(Outcome::Failed) => "failed",
        Some(Outcome::Skipped) => "skipped",
        None => "not run",
    }
}
